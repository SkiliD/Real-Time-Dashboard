MESSAGES: dict[str, dict[str, str]] = {"fr": FR, "en": EN}

# lang cache keyed by (config path, mtime) so a config change is picked up
# immediately, even within one long-lived process (e.g. the GUI server).
_lang_cache: dict = {"key": None, "lang": DEFAULT_LANG}


def get_lang(home: Path | None = None) -> str:
    """Current UI language from config.json (`lang`, default "fr")."""
    h = home or config.devdash_home()
    path = config.config_path(h)
    try:
        key = (str(path), path.stat().st_mtime_ns)
    except OSError:
        key = (str(path), None)
    if _lang_cache["key"] != key:
        lang = config.load_config(h).lang
        _lang_cache["key"] = key
        _lang_cache["lang"] = lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
    return _lang_cache["lang"]


def _fmt(template: str, kwargs: dict) -> str:
    """Replace {name} placeholders; unknown placeholders are left as-is."""
    out = template
    for k, v in kwargs.items():
        out = out.replace("{" + k + "}", str(v))
    return out


def tr(key: str, lang: str | None = None, home: Path | None = None, **kwargs) -> str:
    """Translate `key` into the current language and format {placeholders}."""
    lang = lang or get_lang(home)
    table = MESSAGES.get(lang) or FR
    template = table.get(key) or FR.get(key) or key
    return _fmt(template, kwargs)


def tr_cols(key: str, **kwargs) -> list[str]:
    """Translate a "a|b|c" table-columns string into a list of column names."""
    return tr(key, **kwargs).split("|")


def messages(lang: str | None = None, home: Path | None = None) -> dict[str, str]:
    """Full message table for `lang` (used by the GUI via /api/i18n)."""
    lang = lang or get_lang(home)
    return dict(MESSAGES.get(lang) or FR)
